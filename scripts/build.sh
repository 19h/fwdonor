#!/usr/bin/env bash
# Build fwdonor: vendor zrax at ZRAX_REV, build its WASM and the proof-of-work
# WASM (pow-wasm/), assemble dist/, version and precompress the assets, then
# build the server.
#
#   ZRAX_URL   where to clone zrax from (default: GitHub)
#   SKIP_CARGO set to skip the server build (frontend only)
#   STAGE_DIST set to leave the new frontend in dist.next/ for the caller to
#              swap in (deploy.sh does that right before the restart)
set -euo pipefail
cd -- "$(dirname -- "$0")/.."

ZRAX_URL=${ZRAX_URL:-https://github.com/19h/zrax-isa-workbench.git}
rev=$(tr -d '[:space:]' < ZRAX_REV)

echo "==> zrax @ ${rev:0:12}"
if [ ! -d vendor/zrax/.git ]; then
    mkdir -p vendor
    git clone --quiet "$ZRAX_URL" vendor/zrax
fi
if ! git -C vendor/zrax cat-file -e "$rev^{commit}" 2>/dev/null; then
    git -C vendor/zrax fetch --quiet origin
fi
git -C vendor/zrax checkout --quiet --force "$rev"

echo "==> WASM"
(cd vendor/zrax && wasm-pack build --quiet --release --target web --no-default-features --features wasm)
# The proof-of-work search (target and SIMD come from pow-wasm/.cargo/config.toml).
(cd pow-wasm && cargo build --quiet --release --locked)

# Assemble into dist.next/ so the running server never serves a half-built
# tree, then swap it in (or leave that to the caller with STAGE_DIST).
out=dist.next
echo "==> $out/"
rm -rf "$out"
mkdir -p "$out/fonts" "$out/r" "$out/g" "$out/d/bulk"
cp web/index.html web/*.css web/*.js "$out/"
# Bulk pages, served at /r/<token> and /g/<key> (their asset URLs are ../…).
cp web/bulk.html "$out/r/index.html"
cp web/grant.html "$out/g/index.html"
# The dashboard, served at /d/<key> and /d/<key>/bulk.
cp web/dash.html "$out/d/index.html"
cp web/dash-bulk.html "$out/d/bulk/index.html"
cp vendor/zrax/web/format.js "$out/format.js"
cp vendor/zrax/pkg/zrax.js vendor/zrax/pkg/zrax_bg.wasm "$out/"
cp pow-wasm/target/wasm32-unknown-unknown/release/fwdonor_pow.wasm "$out/pow.wasm"
cp vendor/zrax/web/fonts/*.ttf vendor/zrax/web/fonts/*-OFL.txt "$out/fonts/"
cp vendor/zrax/src/workbench/apeiron/LICENSE "$out/APEIRON-LICENSE.txt"
cp vendor/zrax/docs/third-party-firmware-parsers.txt "$out/THIRD-PARTY-FIRMWARE-PARSERS.txt"
printf "// Generated by scripts/build.sh\nexport const ZRAX_REV = '%s';\n" "$rev" > "$out/build-info.js"

# Version the whole module graph together (as zrax's build-web.sh does), so a
# cached worker or JS glue is never paired with a different WASM binary.
OUT="$out" python3 - <<'PY'
from pathlib import Path
import hashlib, os, re
dist = Path(os.environ['OUT'])
assets = sorted(p for p in dist.rglob('*') if p.suffix in {'.js', '.wasm', '.css', '.ttf'})
revision = hashlib.sha256(b''.join(p.relative_to(dist).as_posix().encode() + b'\0' + p.read_bytes() for p in assets)).hexdigest()[:16]
paths = {p.resolve() for p in assets}
pattern = re.compile(r"(['\"])([^'\"\s?]+\.(?:js|wasm|css|ttf))\1")
for path in assets + sorted(dist.rglob('*.html')):
    if path.suffix not in {'.js', '.css', '.html'}:
        continue
    def version_url(url):
        return f'{url}?v={revision}' if (path.parent / url).resolve() in paths else url
    source = pattern.sub(lambda m: f'{m[1]}{version_url(m[2])}{m[1]}', path.read_text())
    source = re.sub(r'url\(([^)\'"\s?]+\.ttf)\)', lambda m: f'url({version_url(m[1])})', source)
    path.write_text(source)
print(f'    asset revision {revision}')
PY

# Precompress after the rewrite; tower-http serves .br/.gz when accepted.
find "$out" -type f \( -name '*.js' -o -name '*.wasm' -o -name '*.css' -o -name '*.html' -o -name '*.ttf' -o -name '*.txt' \) |
while read -r f; do
    gzip -9 -k -n -f "$f"
    if command -v brotli >/dev/null; then brotli -q 11 -k -f "$f"; fi
done
du -sh "$out" | awk '{print "    " $2 " " $1}'
if [ -z "${STAGE_DIST:-}" ]; then
    rm -rf dist.old
    if [ -d dist ]; then mv dist dist.old; fi
    mv "$out" dist
    rm -rf dist.old
fi

if [ -z "${SKIP_CARGO:-}" ]; then
    echo "==> server"
    cargo build --release --locked
    ls -lh target/release/fwdonor | awk '{print "    " $5 " " $9}'
fi
